create extension if not exists vector with schema extensions;

create table if not exists public.document_chunks (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  source_name text not null,
  chunk_index integer not null,
  content text not null,
  embedding extensions.vector(768) not null,
  created_at timestamptz not null default now(),
  unique (user_id, source_name, chunk_index)
);

alter table public.document_chunks enable row level security;

create policy "Users can view their own document chunks"
on public.document_chunks
for select
to authenticated
using (auth.uid() = user_id);

create policy "Users can insert their own document chunks"
on public.document_chunks
for insert
to authenticated
with check (auth.uid() = user_id);

create policy "Users can delete their own document chunks"
on public.document_chunks
for delete
to authenticated
using (auth.uid() = user_id);

create or replace function public.match_document_chunks(
  query_embedding extensions.vector(768),
  match_user_id uuid,
  match_source_name text,
  match_threshold float,
  match_count int
)
returns table (
  id bigint,
  source_name text,
  chunk_index integer,
  content text,
  similarity float
)
language sql
stable
as $$
  select
    document_chunks.id,
    document_chunks.source_name,
    document_chunks.chunk_index,
    document_chunks.content,
    1 - (document_chunks.embedding <=> query_embedding) as similarity
  from public.document_chunks
  where document_chunks.user_id = match_user_id
    and document_chunks.source_name = match_source_name
    and 1 - (document_chunks.embedding <=> query_embedding) >= match_threshold
  order by document_chunks.embedding <=> query_embedding asc
  limit least(match_count, 20);
$$;

create index if not exists document_chunks_embedding_idx
on public.document_chunks
using hnsw (embedding vector_cosine_ops);

create index if not exists document_chunks_user_source_idx
on public.document_chunks (user_id, source_name);
